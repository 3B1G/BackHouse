LATEST_APPROVAL = "(SELECT id FROM approval WHERE suggestion_id = NEW.suggestion_id ORDER BY id DESC LIMIT 1)"
GUARDS = f"""
CREATE TRIGGER change_log_needs_approval BEFORE INSERT ON change_log
WHEN NOT (
    -- the change cites the owner's latest decision on this suggestion, and that decision is "approved"
    (NEW.approval_id = {LATEST_APPROVAL}
     AND (SELECT decision FROM approval WHERE id = NEW.approval_id) = 'approved')
    -- or it records a bank move that was started under an approval the owner revoked mid-run: what already
    -- happened at the bank must still be logged
    OR (NEW.system = 'nessie' AND EXISTS (SELECT 1 FROM nessie_intent i WHERE i.suggestion_id = NEW.suggestion_id
        AND i.bill_id = NEW.ref AND i.approval_id = NEW.approval_id AND i.to_date = NEW.new_value)))
BEGIN SELECT RAISE(ABORT, 'change_log: not covered by the owner''s latest approved decision'); END;
CREATE TRIGGER change_log_approval_matches BEFORE INSERT ON change_log
WHEN (SELECT suggestion_id FROM approval WHERE id = NEW.approval_id) IS NOT NEW.suggestion_id
BEGIN SELECT RAISE(ABORT, 'change_log: approval is for another suggestion'); END;
CREATE TRIGGER nessie_intent_needs_approval BEFORE INSERT ON nessie_intent
WHEN NOT (NEW.approval_id = {LATEST_APPROVAL} AND (SELECT decision FROM approval WHERE id = NEW.approval_id) = 'approved')
BEGIN SELECT RAISE(ABORT, 'nessie_intent: not covered by the owner''s latest approved decision'); END;
CREATE TRIGGER price_change_matches_log BEFORE INSERT ON price_change
WHEN NOT EXISTS (SELECT 1 FROM change_log c WHERE c.change_id = NEW.change_id AND c.system = 'menu_prices'
                 AND c.field = 'price_cents' AND c.ref = NEW.item AND c.new_value = CAST(NEW.price_cents AS TEXT))
BEGIN SELECT RAISE(ABORT, 'price_change: no matching change_log row'); END;
CREATE TRIGGER availability_change_matches_log BEFORE INSERT ON availability_change
WHEN NOT EXISTS (SELECT 1 FROM change_log c WHERE c.change_id = NEW.change_id AND c.system = 'menu_prices'
                 AND c.field = 'on_menu' AND c.ref = NEW.item
                 AND c.new_value = CASE NEW.available WHEN 1 THEN 'yes' ELSE 'no' END)
BEGIN SELECT RAISE(ABORT, 'availability_change: no matching change_log row'); END;
CREATE TRIGGER dispute_matches_log BEFORE INSERT ON dispute
WHEN NOT EXISTS (SELECT 1 FROM change_log c WHERE c.change_id = NEW.change_id AND c.system = 'other'
                 AND c.field = 'dispute' AND c.ref = NEW.bank_id AND c.new_value = NEW.state)
BEGIN SELECT RAISE(ABORT, 'dispute: no matching change_log row'); END;
CREATE UNIQUE INDEX one_menu_change_per_approval ON change_log (approval_id) WHERE system = 'menu_prices';
CREATE TRIGGER owner_once BEFORE INSERT ON owner WHEN (SELECT count(*) FROM owner) > 0
BEGIN SELECT RAISE(ABORT, 'owner: already set up'); END;
CREATE TRIGGER competitor_role BEFORE INSERT ON competitor
WHEN (cp_role() = 'build') <> (NEW.found_via = 'seed')
BEGIN SELECT RAISE(ABORT, 'competitor: only the build writes seed competitors, and only seed ones'); END;
CREATE TRIGGER competitor_observation_role BEFORE INSERT ON competitor_observation
WHEN (cp_role() = 'build') <> (NEW.reader = 'seed')
BEGIN SELECT RAISE(ABORT, 'competitor_observation: only the build writes seed observations, and only seed ones'); END;
"""

