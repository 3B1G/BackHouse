def ddl() -> str:
    """The full schema. check_schema() compares the live database's sqlite_master with exactly this, statement by
    statement, so a trigger with its body swapped for a no-op is caught even though its name is unchanged."""
    out = [f"CREATE TABLE {t} ({cols}) STRICT;" for t, cols in {**REFERENCE, **HISTORY}.items()]
    for t in HISTORY:
        out.append(f"CREATE TRIGGER {t}_no_update BEFORE UPDATE ON {t} BEGIN SELECT RAISE(ABORT, '{t} is append-only'); END;")
        out.append(f"CREATE TRIGGER {t}_no_delete BEFORE DELETE ON {t} BEGIN SELECT RAISE(ABORT, '{t} is append-only'); END;")
        out.append(f"""CREATE TRIGGER {t}_chain BEFORE INSERT ON {t}
                       WHEN NEW.prev_hash IS NOT COALESCE((SELECT row_hash FROM {t} ORDER BY id DESC LIMIT 1), '{GENESIS}')
                         OR NEW.id IS NOT COALESCE((SELECT max(id) FROM {t}), 0) + 1
                       BEGIN SELECT RAISE(ABORT, '{t}: insert does not continue the hash chain'); END;""")
    out += [GUARDS, VIEWS]
    return "\n".join(out)
