"""DDL for data/cost_price.db. Two layers:

REFERENCE  rebuilt from books.db by `cost-price build` (deterministic; books.db is itself regenerated by generate.py)
HISTORY    append-only, never rebuilt: competitors and their observed prices, scan results, and CH's approved changes.
           Every history row carries prev_hash/row_hash (a per-table hash chain, verified by `cost-price verify`);
           triggers refuse UPDATE/DELETE (also through INSERT OR REPLACE, with recursive_triggers on) and refuse an
           INSERT whose prev_hash doesn't continue the chain.

Conventions: money in integer cents (ingredient unit costs in millicents, cents x 1000, to keep sub-cent precision);
dates YYYY-MM-DD; timestamps YYYY-MM-DDTHH:MM:SSZ (UTC). Dishes are referred to by name, never by a reference-layer
row id, so rebuilding the reference layer can't orphan history rows.

cp_role() is a per-connection function (db.py) naming the connection's role; triggers use it so a role can't write
rows that only another role may write (e.g. the scout can't plant 'seed' observations). A plain sqlite3 connection
without it can't insert into those tables at all."""

SCHEMA_VERSION = 4
GENESIS = "0" * 64


def d(c):
    return f"CHECK ({c} IS NULL OR date({c}) IS {c})"


def ts(c):
    return f"CHECK ({c} IS NULL OR strftime('%Y-%m-%dT%H:%M:%SZ', {c}) IS {c})"


def hexn(c, n):
    return f"CHECK ({c} IS NULL OR (length({c}) = {n} AND NOT {c} GLOB '*[^0-9a-f]*'))"


def text(c, n):
    """1..n characters and no NUL (length() and GLOB stop at a NUL, so it would hide whatever follows)."""
    return f"CHECK ({c} IS NULL OR (instr({c}, char(0)) = 0 AND length({c}) BETWEEN 1 AND {n}))"


def url(c):
    return (f"CHECK (instr({c}, char(0)) = 0 AND length({c}) <= 500 AND ({c} GLOB 'https://?*' OR {c} GLOB 'http://?*'))")


def real(c, lo, hi):
    return f"CHECK ({c} IS NULL OR ({c} = {c} AND {c} BETWEEN {lo} AND {hi}))"     # x = x is false for NaN


